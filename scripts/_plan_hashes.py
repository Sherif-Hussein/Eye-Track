"""SHA-256 hashes and modification times of every analysis-plan file, as a Supplementary LaTeX table.

Usage: python -I scripts/_plan_hashes.py <project_root>
Writes paper/tables/tableS_hashes.tex and results/plan_hashes.csv. Re-run at deposit time so the table matches the deposited files.
"""
import hashlib
import sys
import time
from pathlib import Path

ROOT = Path(sys.argv[1])
pats = ["PREREG*.md", "GO_AHEAD*", "DEVIATIONS*.md", "FREEZE*.md", "*AMENDMENT*"]
files = sorted({p for pat in pats for p in (ROOT / "results").rglob(pat) if p.is_file()})
rows = []
for p in files:
    h = hashlib.sha256(p.read_bytes()).hexdigest()
    rows.append((p.relative_to(ROOT).as_posix(), time.strftime("%Y-%m-%d %H:%M", time.localtime(p.stat().st_mtime)), h))
(ROOT / "results/plan_hashes.csv").write_text("file,modified,sha256\n" + "".join(f"{f},{m},{h}\n" for f, m, h in rows))


def tex(s):
    return s.replace("_", r"\_")


lines = [
    "% Analysis-plan hashes. Generated by scripts/_plan_hashes.py; re-run at deposit time.",
    r"\begin{table}[!htbp]",
    r"\caption{Analysis-plan files. SHA-256 hash (first 16 hex digits) and last modification time of every plan, amendment and deviation log; full hashes are in the deposit (plan\_hashes.csv).}\label{tab:hashes}",
    r"\scriptsize\setlength{\tabcolsep}{3pt}",
    r"\begin{tabular}{@{}llc@{}}",
    r"\toprule",
    r"File & Last modified & SHA-256 (first 16) \\",
    r"\midrule",
]
lines += [rf"\texttt{{{tex(f)}}} & {m} & \texttt{{{h[:16]}}} \\" for f, m, h in rows]
lines += [r"\bottomrule", r"\end{tabular}", r"\end{table}", ""]
(ROOT / "paper/tables/tableS_hashes.tex").write_text("\n".join(lines), encoding="utf-8")
print(len(rows), "files")
for r in rows:
    print(r[1], r[0])
